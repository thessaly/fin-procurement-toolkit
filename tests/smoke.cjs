const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||undefined});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.resolve('index.html'));
 await page.click('[data-act="new-request"]');
 assert.equal(await page.locator('.qcard:visible').count(),1);
 await page.fill('[data-f="objective"]','Research service test');
 await page.click('[data-act="step-next"]');
 await page.click('[data-act="step-back"]');
 assert.equal(await page.inputValue('[data-f="objective"]'),'Research service test');
 await page.selectOption('#requestStep','3');
 await page.check('[data-fs="hosting"]');
 await page.fill('[data-f="deliverable"]','Managed hosting for 12 months');
 await page.fill('[data-f="provider"]','Unknown');
 await page.fill('[data-f="budget"]','EUR 12000');
 await page.selectOption('#requestStep','7');
 await page.check('[data-f="localTested"][value="no"]');
 await page.selectOption('#requestStep','8');
 await page.click('a[href="#review"]');
 assert.match(await page.locator('body').innerText(),/Managed hosting for 12 months/);
 await page.check('[name="a-need"][value="followup"]');
 assert.match(await page.locator('#reviewProgress').innerText(),/^1\//);
 await page.goto('file://'+path.resolve('index.html')+'#home');
 await page.click('[data-act="example-request"]');
 await page.selectOption('#requestStep','3');
 assert.match(await page.inputValue('[data-f="deliverable"]'),/12-month managed JupyterHub/);
 assert.match(await page.inputValue('[data-f="provider"]'),/fictional/);
 const md=await page.evaluate(()=>caseMarkdown(CASE));
 assert.match(md,/EUR 12,000/);assert.match(md,/Illustrative example/);
 assert.equal(await page.evaluate(()=>evidenceLabel([],null)),'No information available');
 assert.equal(await page.evaluate(()=>evidenceLabel([{ok:true}],{ok:true,errors:[]})),'Information retrieved');
 assert.equal(await page.evaluate(()=>evidenceLabel([{ok:true}],{ok:true,example:true})),'Needs review');
 await page.goto('file://'+path.resolve('index.html')+'#review');
 assert.match(await page.locator('body').innerText(),/Needs review/);
 await page.goto('file://'+path.resolve('index.html')+'#report');
 assert.match(await page.locator('#reportDoc').innerText(),/EUR 12,000/);
 await page.goto('file://'+path.resolve('index.html')+'#home');
 await page.screenshot({path:'/tmp/fin-home.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.click('[data-act="example-request"]');
 await page.selectOption('#requestStep','5');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'/tmp/fin-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 await browser.close();console.log('PASS: guided navigation, input persistence, procurement fields, review progress, evidence states, exports, desktop/mobile layout; no page errors.');
})().catch(e=>{console.error(e);process.exit(1)});
